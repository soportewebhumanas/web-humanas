                                La Facultad de Ciencias Humanas se organizó a fines de 1970, doce años despúes de la fundación de la Universidad de La Pampa. El 2 de octubre de ese año, la aspiración del Instituto Provincial del Profesorado de convertirse en Facultad se alcanzó mediante el Decreto Provincial 1.589. La novel Unidad Académica, con sede inicial en la ciudad de Santa Rosa, otorgaba los títulos de Profesor de Historia y Geografía, Literatura y Castellano, e Idioma Inglés. En 1972 se creó el Departamento de Filosofía y Pedagogía en General Pico, consolidando así la presencia de la Facultad en esa ciudad.
