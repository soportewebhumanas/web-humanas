                                Después de la normalización institucional de los años ochenta, la Facultad de Ciencias Humanas atravesó un proceso de crecimiento que se tradujo en el fortalecimiento de su planta docente, la ampliación de su oferta académica, el incremento de su matrícula, el desarrollo de los campos de investigación y extensión mediante la creación de institutos, la edición de revistas científicas y la organización de proyectos coparticipativos con diversos actores sociales, con la convicción creciente de que es su deber el garantizar el derecho a la educación universitaria.
                                Con medio siglo de historia, la Facultad de Ciencias Humanas trabaja junto a la comunidad en la construcción colectiva de una Universidad pública, gratuita, laica, inclusiva y diversa. Desarrolla de manera articulada las tres funciones sustantivas de la Educación Superior en sus tres sedes: Santa Rosa, General Pico y General Acha. Cuenta con nueve departamentos: Historia, Geografía, Letras, Lenguas Extranjeras, Educación Inicial, Educación Primaria, Ciencias de la Educación, Formación Docente y Comunicación Social. Posee una oferta académica amplia, que incluye 17 carreras de grado, 2 maestrías y 3 especializaciones. Además, en su ámbito funcionan el Colegio de la Universidad Nacional de La Pampa, 9 institutos de investigación y 8 revistas científicas.                            
